# Requirements
# 1. สร้างตัวแปรเก็บชื่อสินค้าเป็น "Milk"
# 2. ราคาต่อชิ้นเท่ากับ 35.50 บาท
# 3. จำนวนสินค้าในสต็อกเท่ากับ 12 ชิ้น
# 4. สร้างตัวแปรเก็บสถานะว่าสินค้ายังมีจำหน่าย (True)
# 5. คำนวณมูลค่าสินค้าคงเหลือทั้งหมด
# 6. แสดงผลให้มีชื่อสินค้า ราคา จำนวน สถานะ และมูลค่ารวม

product_name = "Milk" #ตั้งตัวแปรชื่อสินค้า
price = 35.50 # ตั้งตัวแปรกำหนดราคา
quantity = 12 # ตั้งตัวแปรกำหนดปริมาณ
is_available = True #กำหนดตัวแปรเพื่อกำหนดว่ามีสินค้าหรือไม่ 
total_value = price * quantity   #ตัวแปรคำนวณมูลค่าสินค้า

print("ชื่อสินค้า" ,product_name)  # แสดงผลข้อมูล
print("ราคา" ,price)
print("จำนวนสินค้า", quantity)
print("สถานะ",is_available)
print("มูลค่ารวม", total_value)